#!/usr/bin/env bash
# Review-pinned redistribution texts for the committed linux/amd64 executable.
set -euo pipefail
cd "$(dirname "$0")"
export GOTOOLCHAIN="${GOTOOLCHAIN:-local}"
export GOOS=linux GOARCH=amd64 GOAMD64=v1 GOEXPERIMENT= GOFLAGS=-mod=readonly
case "${1:-}" in
    '') write=false ;;
    --write) write=true ;;
    *) echo 'Usage: bash backend/check-licenses.sh [--write]' >&2; exit 1 ;;
esac
test "$#" -le 1
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
fail() { echo "License check: $*" >&2; exit 1; }

# A dependency/toolchain change requires reviewing its terms, not just accepting
# whatever LICENSE happens to exist. Include optional AUTHORS/PATENTS verbatim.
compiler=go1.27.3
components=(
    'golang.org/x/net|v0.62.0|LICENSE PATENTS'
    'golang.org/x/sys|v0.49.0|LICENSE PATENTS'
    'golang.org/x/text|v0.43.0|LICENSE PATENTS'
    'google.golang.org/genproto/googleapis/rpc|v0.0.0-20260706201446-f0a921348800|LICENSE'
    'google.golang.org/grpc|v1.84.0|LICENSE NOTICE.txt AUTHORS'
    'google.golang.org/protobuf|v1.36.12|LICENSE PATENTS'
)
test "$(go env GOVERSION)" = "$compiler" || fail "Use reviewed compiler $compiler"
test "go$(awk '$1 == "go" {print $2}' go.mod)" = "$compiler" || fail 'Review the new go.mod compiler'
go version -m bin/starlinkd > "$work/metadata"
test "$(head -n 1 "$work/metadata")" = "bin/starlinkd: $compiler" || fail 'Binary compiler differs from reviewed compiler'
grep -Fq 'GOARCH=amd64' "$work/metadata" || fail 'Review the binary architecture'
grep -Fq 'GOOS=linux' "$work/metadata" || fail 'Review the binary OS'
if grep -Eq '^[[:space:]]*=>' "$work/metadata"; then
    fail 'Module replacements require notice review'
fi
awk '$1 == "dep" {print $2 "|" $3}' "$work/metadata" | sort > "$work/actual"
printf '%s\n' "${components[@]}" | cut -d '|' -f 1,2 | sort > "$work/expected"
cmp -s "$work/actual" "$work/expected" || fail 'Linked module inventory changed; review dependency licenses'

append() {
    local component=$1 source=$2 file=$3
    test -s "$source" || fail "Missing upstream text: $component/$file"
    printf '\n===== %s / %s =====\n\n' "$component" "$file" >> "$work/notices"
    cat "$source" >> "$work/notices"
    printf '\n' >> "$work/notices"
}
cat > "$work/notices" <<'EOF'
Third-party notices for backend/bin/starlinkd (linux/amd64)

Dishy's own code is MIT-licensed; see ../LICENSE. The statically linked
components below retain their upstream terms. These texts accompany the
executable in the plugin checkout; retain them when redistributing it.
Generated by check-licenses.sh from the reviewed compiler/module versions.
EOF
goroot=$(go env GOROOT)
append "Go $compiler" "$goroot/LICENSE" LICENSE
append "Go $compiler" "$goroot/PATENTS" PATENTS
# The amd64 runtime also contains Inferno-derived assembly. Retain its complete
# copyright/permission header, not just Go's top-level BSD license.
sed -n '1,24s@^// *@@p' "$goroot/src/runtime/memmove_amd64.s" > "$work/runtime-notice"
grep -Fq 'Lucent Technologies' "$work/runtime-notice" || fail 'Review the runtime assembly notice'
grep -Fq 'THE SOFTWARE.' "$work/runtime-notice" || fail 'Runtime assembly notice is incomplete'
append "Go $compiler" "$work/runtime-notice" src/runtime/memmove_amd64.s
for component in "${components[@]}"; do
    IFS='|' read -r module version files <<< "$component"
    go list -m -json "$module" > "$work/module"
    jq -e --arg m "$module" --arg v "$version" \
        '.Path == $m and .Version == $v and .Replace == null' "$work/module" > /dev/null \
        || fail "Resolved module differs: $module@$version"
    dir=$(jq -er .Dir "$work/module")
    for file in $files; do
        append "$module@$version" "$dir/$file" "$file"
    done
done
if "$write"; then
    # Validate everything before replacing the distributed file.
    install -m 644 "$work/notices" THIRD_PARTY_NOTICES.txt
else
    cmp -s THIRD_PARTY_NOTICES.txt "$work/notices" \
        || fail 'THIRD_PARTY_NOTICES.txt missing/stale; review, then run check-licenses.sh --write'
fi
echo "Bundled license/notice check passed ($compiler, ${#components[@]} modules)"
